//! Renders `docs/dev/operations/cli-commands.md` from the command line's clap
//! model, so it says what `--help` says, and checks the committed page is
//! current. `just docs reference` rewrites it.

use super::Cli;
use clap::{Arg, ArgAction, Command, CommandFactory};
use piquel_common::config::GeneratedFile;
use std::fmt::Write as _;

/// The page's title and introduction, after the generated-file comment.
const INTRO: &str = "\
# auth-service commands

This page lists every `auth-service` command with its arguments and options. It
is generated from the same definitions as `auth-service --help`, so `--help` on
any command prints the same text. [Administration](administration.md) shows the
commands at work, and [deploying](deploying.md#running-auth-service-commands)
how to run them in an environment.

Every command also accepts `-h` and `--help`.
";

/// The page, built one command at a time, depth first.
struct Reference {
    /// The Markdown written so far.
    page: String,
}

impl Reference {
    /// Renders the page from the whole command tree.
    fn render() -> String {
        let mut command = Cli::command().bin_name("auth-service");
        // Building fills in each subcommand's full name and its usage.
        command.build();
        let mut reference = Self {
            page: format!(
                "<!-- Generated by `just docs reference` from the clap definitions in \
                 `apps/auth-service/src/cli`. Do not edit it by hand. -->\n\n{INTRO}"
            ),
        };
        reference.command(&command);
        reference.page
    }

    /// Adds `command`'s section: what it does, its usage, its arguments and
    /// options, and links to its subcommands, whose sections follow.
    fn command(&mut self, command: &Command) {
        let path = command.get_bin_name().unwrap_or(command.get_name());
        let _ = writeln!(self.page, "\n## `{path}`\n");
        if let Some(about) = command.get_long_about().or(command.get_about()) {
            let _ = writeln!(self.page, "{}\n", Self::sentence(&about.to_string()));
        }
        let usage = command.clone().render_usage().to_string();
        let _ = writeln!(
            self.page,
            "```text\n{}\n```",
            usage.trim_start_matches("Usage: ")
        );

        let (positionals, options): (Vec<&Arg>, Vec<&Arg>) = command
            .get_arguments()
            .filter(|argument| Self::documented(argument))
            .partition(|argument| argument.is_positional());
        for (title, arguments) in [("Arguments", positionals), ("Options", options)] {
            if !arguments.is_empty() {
                let _ = writeln!(self.page, "\n{title}:\n");
                for argument in arguments {
                    self.argument(argument);
                }
            }
        }

        let subcommands: Vec<&Command> = command
            .get_subcommands()
            // clap's own `help` command is the `--help` the introduction covers.
            .filter(|subcommand| !subcommand.is_hide_set() && subcommand.get_name() != "help")
            .collect();
        if !subcommands.is_empty() {
            let _ = writeln!(self.page, "\nCommands:\n");
            for subcommand in &subcommands {
                let name = format!("{path} {}", subcommand.get_name());
                let about = subcommand
                    .get_about()
                    .map(|about| Self::sentence(&about.to_string()))
                    .unwrap_or_default();
                let _ = writeln!(
                    self.page,
                    "- [`{name}`](#{}): {about}",
                    name.replace(' ', "-")
                );
            }
        }
        for subcommand in subcommands {
            self.command(subcommand);
        }
    }

    /// Adds one argument or option: how to write it, what it does, and its
    /// default and accepted values.
    fn argument(&mut self, argument: &Arg) {
        let syntax = match (argument.get_short(), argument.get_long()) {
            (Some(short), Some(_)) => format!("-{short}, {argument}"),
            _ => argument.to_string(),
        };
        let help = argument
            .get_long_help()
            .or(argument.get_help())
            .map(|help| Self::sentence(&help.to_string()))
            .unwrap_or_default();
        let mut text = format!("`{syntax}`: {help}");
        if argument.is_required_set() && !argument.is_positional() {
            text.push_str(" Required.");
        }
        let takes_values = argument.get_action().takes_values();
        let defaults: Vec<String> = argument
            .get_default_values()
            .iter()
            .map(|value| format!("`{}`", value.to_string_lossy()))
            .filter(|value| value != "``")
            .collect();
        if takes_values && !defaults.is_empty() {
            let _ = write!(text, " Default: {}.", defaults.join(", "));
        }
        let values: Vec<String> = argument
            .get_possible_values()
            .iter()
            .filter(|value| !value.is_hide_set())
            .map(|value| match value.get_help() {
                Some(help) => format!("`{}` ({})", value.get_name(), help),
                None => format!("`{}`", value.get_name()),
            })
            .collect();
        if takes_values && !values.is_empty() {
            let _ = write!(text, " Values: {}.", values.join(", "));
        }
        let _ = writeln!(self.page, "- {}", text.trim_end());
    }

    /// Whether `argument` belongs on the page: not hidden, and not clap's own
    /// `--help` and `--version`, which the introduction covers.
    fn documented(argument: &Arg) -> bool {
        !argument.is_hide_set()
            && !matches!(
                argument.get_action(),
                ArgAction::Help | ArgAction::HelpShort | ArgAction::HelpLong | ArgAction::Version
            )
    }

    /// `text` as prose: clap's help drops a summary's final full stop, so it
    /// gets one back, and its paragraphs keep their blank lines.
    fn sentence(text: &str) -> String {
        let text = text.trim();
        if text.is_empty() || text.ends_with(['.', ':', '!', '?']) {
            text.to_owned()
        } else {
            format!("{text}.")
        }
    }
}

/// The committed page says what the command line's definitions say.
#[test]
fn cli_reference_is_current() {
    GeneratedFile {
        path: concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../docs/dev/operations/cli-commands.md"
        )
        .into(),
        text: Reference::render(),
    }
    .write_or_compare()
    .expect("current reference");
}
